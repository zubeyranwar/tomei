import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { basename, join, relative } from 'node:path'
import { pathToFileURL } from 'node:url'

import { kindTypes, scenarios, type Kind, type Scenario } from '../registry/config'
import type { IndexedItem, ItemMeta } from '../registry/define'
import { site } from '../lib/site'

const ROOT = process.cwd()
const REGISTRY = join(ROOT, 'registry')
const NOT_SHIPPED = new Set(['item.ts', 'demo.tsx', 'prompt.md'])
const NAME = /^[a-z0-9]+(-[a-z0-9]+)*$/

const dirs = (path: string) =>
  existsSync(path) ? readdirSync(path).filter((d) => statSync(join(path, d)).isDirectory()) : []

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry)
    return statSync(path).isDirectory() ? walk(path) : [path]
  })

const fail = (message: string): never => {
  console.error(`\x1b[31m✖ registry:\x1b[0m ${message}`)
  process.exit(1)
}

const entries: IndexedItem[] = []

for (const scenario of Object.keys(scenarios) as Scenario[]) {
  const kinds = scenarios[scenario].kinds as readonly Kind[]
  for (const kind of dirs(join(REGISTRY, scenario))) {
    if (!kinds.includes(kind as Kind))
      fail(`registry/${scenario}/${kind} is not a kind of "${scenario}" (${kinds.join(', ')})`)

    for (const name of dirs(join(REGISTRY, scenario, kind))) {
      const dir = join(REGISTRY, scenario, kind, name)
      const rel = relative(ROOT, dir)
      if (!NAME.test(name)) fail(`${rel}: folder name must be kebab-case`)
      if (entries.some((e) => e.name === name))
        fail(`${rel}: "${name}" already exists — names are unique across the registry`)
      if (!existsSync(join(dir, 'item.ts'))) fail(`${rel}: missing item.ts`)
      if (!existsSync(join(dir, 'demo.tsx'))) fail(`${rel}: missing demo.tsx`)

      const files = walk(dir)
        .filter((f) => !NOT_SHIPPED.has(relative(dir, f)))
        .map((f) => relative(ROOT, f))
        .sort(
          (a, b) =>
            Number(basename(b).startsWith(`${name}.`)) - Number(basename(a).startsWith(`${name}.`)),
        )
      if (!files.length) fail(`${rel}: no files to ship besides item.ts/demo.tsx`)

      const meta: ItemMeta = (await import(pathToFileURL(join(dir, 'item.ts')).href)).default
      entries.push({
        ...meta,
        name,
        scenario,
        kind: kind as Kind,
        dir: rel,
        files,
        hasPrompt: existsSync(join(dir, 'prompt.md')),
      })
    }
  }
}

entries.sort((a, b) => (b.date ?? '').localeCompare(a.date ?? '') || a.name.localeCompare(b.name))

const registry = {
  $schema: 'https://ui.shadcn.com/schema/registry.json',
  name: 'tomei',
  homepage: site.url,
  items: entries.map((e) => ({
    name: e.name,
    type: kindTypes[e.kind],
    title: e.title,
    description: e.description,
    author: `${site.author} <${site.authorUrl}>`,
    ...(e.docs && { docs: e.docs }),
    ...(e.categories?.length && { categories: [e.scenario, ...e.categories] }),
    ...(e.dependencies?.length && { dependencies: e.dependencies }),
    ...(e.devDependencies?.length && { devDependencies: e.devDependencies }),
    ...(e.registryDependencies?.length && { registryDependencies: e.registryDependencies }),
    ...(e.cssVars && { cssVars: e.cssVars }),
    ...(e.css && { css: e.css }),
    files: e.files.map((path) => ({
      path,
      type: 'registry:component',
      target:
        e.files.length === 1
          ? `components/${e.scenario}/${basename(path)}`
          : `components/${e.scenario}/${e.name}/${relative(e.dir, path)}`,
    })),
    meta: { scenario: e.scenario, kind: e.kind },
  })),
}

writeFileSync(join(ROOT, 'registry.json'), JSON.stringify(registry, null, 2) + '\n')

const index = `// Generated by scripts/registry-index.ts — do not edit.
import type { ComponentType } from 'react'

import type { IndexedItem } from '@/registry/define'

export const items: IndexedItem[] = ${JSON.stringify(entries, null, 2)}

export const demos: Record<string, () => Promise<{ default: ComponentType }>> = {
${entries.map((e) => `  '${e.name}': () => import('@/${e.dir}/demo'),`).join('\n')}
}
`

writeFileSync(join(REGISTRY, '__index__.ts'), index)
console.log(`\x1b[32m✔ registry:\x1b[0m indexed ${entries.length} item(s)`)
