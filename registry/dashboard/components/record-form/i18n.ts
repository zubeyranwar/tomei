export type MessageKey = keyof typeof en
export type Messages = Partial<Record<MessageKey | (string & {}), string>>
export type Translate = (key: string, vars?: Record<string, unknown>) => string | undefined
export type T = (key: MessageKey | (string & {}), vars?: Record<string, unknown>) => string

const fill = (template: string, vars: Record<string, unknown> = {}) =>
  template.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] === undefined ? `{${k}}` : String(vars[k]),
  )

export function createT(
  options: { translate?: Translate; messages?: Messages; locale?: string } = {},
): T {
  const plural = new Intl.PluralRules(options.locale ?? 'en')
  const lookup = (key: string, vars?: Record<string, unknown>) =>
    options.translate?.(key, vars) ?? options.messages?.[key] ?? (en as Record<string, string>)[key]
  return (key, vars) => {
    if (vars && typeof vars.count === 'number') {
      const form = plural.select(vars.count)
      const found = lookup(`${key}_${form}`, vars) ?? lookup(`${key}_other`, vars)
      if (found) return fill(found, vars)
    }
    const found = lookup(key, vars)
    return found === undefined ? key : fill(found, vars)
  }
}

export const defaultT = createT()
